"""BibTeX citation export for any paper in the library.

Builds a conventional BibTeX entry from the paper's stored metadata:
article @-type, first-author+year citekey, protected titles, page/venue fields
when known. Deterministic - no LLM involved.
"""
from __future__ import annotations

import re

from app.models.entities import Paper


def _citekey(paper: Paper) -> str:
    authors = paper.authors or []
    last = ""
    if authors:
        first_name = (authors[0].get("name") or "").strip()
        parts = first_name.split()
        last = parts[-1] if parts else ""
    last = re.sub(r"[^a-zA-Z]", "", last).lower() or "unknown"
    year = paper.year or "nd"
    return f"{last}{year}"


def _clean(value: str | None) -> str:
    return re.sub(r"\s+", " ", (value or "")).strip()


def bibtex_for(paper: Paper) -> str:
    key = _citekey(paper)
    title = _clean(paper.title or paper.filename or "Untitled").replace("{", "").replace("}", "")
    authors = " and ".join(
        _clean(a.get("name")) for a in (paper.authors or []) if a.get("name")
    ) or "Unknown"

    fields = [
        ("title", f"{{{title}}}"),
        ("author", f"{{{authors}}}"),
        ("year", str(paper.year or "n.d.")),
    ]
    if paper.venue:
        fields.append(("journal", f"{{{paper.venue}}}"))
    if paper.doi:
        fields.append(("doi", paper.doi))
    if paper.arxiv_id:
        fields.append(("eprint", paper.arxiv_id))
        fields.append(("archivePrefix", "arXiv"))
    if paper.openalex_id:
        fields.append(("url", f"https://openalex.org/{paper.openalex_id}"))
    note = "Generated by ScholarScout from the uploaded paper's metadata."
    fields.append(("note", note))

    body = ",\n  ".join(f"{k} = {v}" for k, v in fields)
    return f"@article{{{key},\n  {body}\n}}"


def ris_for(paper: Paper) -> str:
    """RIS export (Zotero/EndNote friendly)."""
    lines = ["TY  - JOUR"]
    if paper.title:
        lines.append(f"TI  - {_clean(paper.title)}")
    for a in (paper.authors or []):
        if a.get("name"):
            lines.append(f"AU  - {_clean(a['name'])}")
    if paper.year:
        lines.append(f"PY  - {paper.year}")
    if paper.venue:
        lines.append(f"JO  - {_clean(paper.venue)}")
    if paper.doi:
        lines.append(f"DO  - {paper.doi}")
    if paper.abstract:
        lines.append(f"AB  - {_clean(paper.abstract)[:800]}")
    lines.append("ER  - ")
    return "\n".join(lines)
